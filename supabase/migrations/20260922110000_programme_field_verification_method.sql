-- План 2026-09-21, неделя 3, пункт 01: подтверждение правил разметки
-- вместо подтверждения 891 строки по одной.
--
-- Направление программы не входит в перечень фактов правила 6 CLAUDE.md
-- (конкурсная формула, дедлайн подачи, стоимость и бюджетные места,
-- языковое требование, через кого подача) — ошибка здесь означает, что
-- программа нашлась не в том фильтре интересов, а не что человек подал
-- документы не туда. Поэтому вместо разбора 891 строки в Studio владелец
-- читает и утверждает НАБОР ПРАВИЛ (pipeline/src/programme_fields.py) и
-- отдельно проверяет случайную выборку размеченных программ
-- (docs/checks/PROGRAMME-FIELD-REVIEW.md); после этого
-- confirm_programme_fields_by_rule.py подтверждает разметку разом.
--
-- verification_method различает такое пакетное подтверждение от ручного
-- построчного (на случай, если позже для какой-то спорной программы
-- потребуется свериться руками) — "в базе отдельный вид подтверждения,
-- отличимый от ручного" (план). Ограничение ниже не даёт подтвердить
-- запись, не указав, каким способом.
alter table programme_field
  add column verification_method text check (verification_method in ('manual', 'rule')),
  add constraint programme_field_verified_needs_method
    check (verified_at is null or verification_method is not null);
