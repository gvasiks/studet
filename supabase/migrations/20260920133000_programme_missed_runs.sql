-- Устаревшие программы (план работ, неделя 2). Конвейер только добавляет и
-- обновляет строки, поэтому программа, которую вуз закрыл, вечно оставалась
-- бы в каталоге (так случилось с BSA "Digital Visualization Design": страница
-- отдаёт 404, а в базе программа жила).
--
-- missed_runs — сколько прогонов ПОДРЯД источник успешно отработал (прошёл
-- проверку полноты), но этой программы на сайте не нашёл. Найдена — счётчик
-- обнуляется. Со 2-го пропуска программа скрывается для всех, кроме
-- сервисного ключа (политика ниже): пропуск в один прогон может быть
-- случайным, два подряд — уже закрытая программа.
--
-- Порог 2 живёт в двух местах: здесь и в HIDE_AFTER_MISSED_RUNS
-- (pipeline/src/main.py). Менять — в обоих.
--
-- source_key — какой источник записал строку. Нужен, потому что у одного
-- вуза бывает два источника (РТУ: каталог и Лиепая): без него прогон одного
-- считал бы программы другого "не найденными". У строк, записанных до этой
-- миграции, он пуст; первый полный прогон проставит его всем найденным, а
-- непроставленные — как раз те, что не нашлись.
--
-- Скрытие — в RLS, а не в запросах приложения (OWASP A01): один фильтр
-- вместо десяти, который легко забыть в новой странице. Сервисный ключ
-- политики RLS обходит, конвейер и очередь проверки видят всё.

alter table programme
  add column source_key text,
  add column missed_runs integer not null default 0 check (missed_runs >= 0);

drop policy programme_public_read on programme;
create policy programme_public_read on programme for select using (missed_runs < 2);
