-- Страна у вуза. До этого в проекте была одна страна, и понятия «страна»
-- в схеме не было. С решением 2026-10-05 (Литва, запуск 1 июня 2027,
-- docs/PLAN-LITHUANIA-2027.md) каталог становится двухстрановым: каждая
-- страница сайта показывает вузы только своей страны.
--
-- Страна хранится у вуза, а не у программы: программа всегда принадлежит
-- одному вузу, и второго места, где её можно было бы перепутать, не нужно.
--
-- Значения — двухбуквенные коды ISO 3166-1. Все существующие строки
-- получают 'LV' через значение по умолчанию; латвийский конвейер ничего
-- не меняет и продолжает создавать латвийские вузы.
--
-- Права доступа (RLS) не меняются: колонка публичная, как и остальные
-- поля вуза.

alter table university
  add column country text not null default 'LV'
  check (country in ('LV', 'LT'));

comment on column university.country is
  'ISO 3166-1 alpha-2. Определяет, в каталоге какой страны показывается вуз.';
